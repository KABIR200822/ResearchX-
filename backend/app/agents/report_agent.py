
import json
from datetime import datetime

from app.tools.gemini_client import generate_text


def generate_report(
    query: str,
    papers: list,
    analyses: list,
    fact_check: dict
) -> dict:
    """
    Generate a Gemini-powered research report
    using the outputs of previous ResearchX agents.
    """

    report_date = datetime.now().strftime("%Y-%m-%d")
    total_papers = len(papers)

    # Prepare compact paper information
    paper_information = []

    for index, paper in enumerate(papers, start=1):
        paper_information.append({
            "paper_number": index,
            "paper_id": paper.get("paper_id", ""),
            "title": paper.get("title", "Untitled"),
            "authors": paper.get("authors", []),
            "published": paper.get("published", ""),
            "source_url": paper.get("source_url", ""),
            "abstract": paper.get("abstract", "")
        })

    # Prepare analysis information
    analysis_information = []

    for result in analyses:
        analysis_information.append({
            "paper_id": result.get("paper_id", ""),
            "title": result.get("title", "Untitled"),
            "analysis": result.get("analysis", {})
        })

    # Prepare evidence information
    evidence_information = {
        "total_evidence_checked": fact_check.get(
            "total_evidence_checked", 0
        ),
        "verified_evidence": fact_check.get(
            "verified_evidence", []
        ),
        "unverified_evidence": fact_check.get(
            "unverified_evidence", []
        ),
        "potential_conflicts": fact_check.get(
            "potential_conflicts", []
        ),
        "conflicts_found": fact_check.get(
            "conflicts_found", 0
        ),
        "verification_type": fact_check.get(
            "verification_type", "Not specified"
        )
    }

    prompt = f"""
You are the research report generation agent of ResearchX.

Generate a professional, detailed academic research report.

RESEARCH TOPIC:
{query}

PAPERS:
{json.dumps(paper_information, ensure_ascii=False)}

AI ANALYSIS:
{json.dumps(analysis_information, ensure_ascii=False)}

EVIDENCE CHECK RESULTS:
{json.dumps(evidence_information, ensure_ascii=False)}

REPORT REQUIREMENTS:

Write the report in Markdown.

Include these sections:

1. Executive Summary
2. Research Overview
3. Research Papers and Their Contributions
4. Cross-Paper Findings
5. Benefits and Applications
6. Limitations and Research Gaps
7. Evidence Verification
8. Potential Evidence Conflicts
9. Research Limitations
10. Conclusion

IMPORTANT RULES:

- Use only the information supplied above.
- Do not invent papers, authors, statistics, findings or citations.
- Distinguish information explicitly supported by abstracts
  from AI-generated interpretations.
- Explain potential conflicts without calling them
  confirmed scientific contradictions.
- Mention that abstract-based evidence screening
  requires human review of original papers.
- If information is unavailable, state that clearly.
- Keep the writing professional and academically neutral.
- Do not claim that the evidence checker proves scientific truth.
- Do not repeat the complete abstracts unnecessarily.

Return only the Markdown report.
"""

    report_content = generate_text(prompt)

    if not report_content:
        raise ValueError("Gemini returned an empty research report.")

    # Preserve original paper metadata in the final report
    metadata_lines = [
        "# ResearchX Research Report",
        "",
        f"**Research Topic:** {query}",
        f"**Generated On:** {report_date}",
        f"**Papers Retrieved:** {total_papers}",
        "",
        "---",
        "",
        report_content,
        "",
        "---",
        "",
        "## Appendix: Retrieved Paper Sources",
        ""
    ]

    for index, paper in enumerate(papers, start=1):
        metadata_lines.extend([
            f"### {index}. {paper.get('title', 'Untitled')}",
            "",
            f"**Authors:** {', '.join(paper.get('authors', [])) or 'Not available'}",
            f"**Publication Date:** {paper.get('published') or 'Not available'}",
            f"**Source:** {paper.get('source_url') or 'Not available'}",
            ""
        ])

    metadata_lines.extend([
        "*Generated by ResearchX Research Pipeline*"
    ])

    final_report = "\n".join(metadata_lines)

    return {
        "report_title": f"Research Report: {query}",
        "generated_on": report_date,
        "total_papers": total_papers,
        "format": "Markdown",
        "content": final_report
    }
